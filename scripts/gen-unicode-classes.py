#!/usr/bin/env python3
"""SP-174 / T-0601 — generate ScriviCore/src/markdown/UnicodeClasses.hpp.

The core's word range (a port of Apple's `ManuscriptCommands.wordRange`) needs Apple's two character classes for a UTF-16 unit:
  word  = CharacterSet.alphanumerics            → Unicode general categories L*, M*, N*
  punct = CharacterSet.punctuationCharacters ∪ CharacterSet.symbols → P*, S*
The core has no ICU, so the BMP ranges are generated here from Python's Unicode database (a surrogate half is handled by the
caller: Apple treats it as part of a letter). Re-run when the Unicode version matters:  python3 scripts/gen-unicode-classes.py
"""
import pathlib, unicodedata

def ranges(pred, lo=0, hi=0x10000):
    out, start = [], None
    for cp in range(lo, hi):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(unicodedata.category(chr(cp)))
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, hi - 1))
    return out

word = ranges(lambda c: c[0] in "LMN")
punct = ranges(lambda c: c[0] in "PS")
# The emphasis normalizer needs md4c's view of a SUPPLEMENTARY-plane scalar too (an emoji is S*, so `x**👋` cannot open).
punct32 = ranges(lambda c: c[0] in "PS", 0x10000, 0x110000)

def table(name, rs, kind="Range16"):
    rows = ",\n".join("    {0x%04X, 0x%04X}" % r for r in rs)
    return f"inline constexpr {kind} {name}[] = {{\n{rows}\n}};\n"

hdr = f'''#pragma once
// ⚠️ GENERATED by scripts/gen-unicode-classes.py — do not edit. Unicode {unicodedata.unidata_version} (Python's database).
// SP-174 / T-0601: Apple's `CharacterSet.alphanumerics` (L*, M*, N*) and `punctuationCharacters ∪ symbols` (P*, S*) for one
// UTF-16 unit of the BMP. ⚠️ Apple's Foundation may know a newer Unicode; the two differ only for characters added since.

#include <algorithm>
#include <cstdint>
#include <iterator>

namespace scrivi::markdown::unicode {{

struct Range16 {{ char16_t first; char16_t last; }};
struct Range32 {{ char32_t first; char32_t last; }};

{table("kWordRanges", word)}
{table("kPunctRanges", punct)}
{table("kPunctRangesSupplementary", punct32, "Range32")}
template <typename R, std::size_t N, typename C>
constexpr bool inRanges(const R (&rs)[N], C c) {{
    const auto* it = std::upper_bound(std::begin(rs), std::end(rs), c,
                                      [](C v, const R& r) {{ return v < r.first; }});
    return it != std::begin(rs) && c <= std::prev(it)->last;
}}

// Apple's `CharacterSet.alphanumerics` for a BMP unit (the caller treats a surrogate half as a letter).
constexpr bool isAlphanumeric(char16_t c) {{ return inRanges(kWordRanges, c); }}
// Apple's `CharacterSet.punctuationCharacters ∪ symbols` for a BMP unit.
constexpr bool isPunctuationOrSymbol(char16_t c) {{ return inRanges(kPunctRanges, c); }}
// CommonMark's (md4c's) Unicode punctuation for one SCALAR, any plane: P* and S*.
constexpr bool isPunctuationOrSymbolScalar(char32_t c) {{
    return c < 0x10000 ? inRanges(kPunctRanges, static_cast<char16_t>(c)) : inRanges(kPunctRangesSupplementary, c);
}}

}} // namespace scrivi::markdown::unicode
'''
out = pathlib.Path(__file__).resolve().parent.parent / "ScriviCore/src/markdown/UnicodeClasses.hpp"
out.write_text(hdr)
print(f"wrote {out} — {len(word)} word ranges, {len(punct)} punctuation/symbol ranges")
